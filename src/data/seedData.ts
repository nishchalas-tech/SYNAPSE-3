// Helper to create inventory matrix cleanly
function makeInv(
  storeId: string,
  productId: string,
  recordedQty: number,
  verifiedQty: number,
  reservedQty: number,
  safetyBuffer: number,
  hoursAgo: number,
  verifiedBy: string,
  discrepancyReason?: string
): InventoryRecord {
  const cartHoldQty = 0;
  const sellableQty = Math.max(0, verifiedQty - reservedQty - cartHoldQty - safetyBuffer);
  return {
    id: `${storeId}_${productId}`,
    storeId,
    productId,
    recordedQty,
    verifiedQty,
    reservedQty,
    cartHoldQty,
    sellableQty,
    safetyBuffer,
    lastVerifiedAt: hoursAgoIso(hoursAgo),
    lastVerifiedBy: verifiedBy,
    discrepancyReason,
    updatedAt: hoursAgoIso(hoursAgo),
  };
}

